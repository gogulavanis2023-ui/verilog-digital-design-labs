module binary_to_segment(
    input [3:0] bin,
    output reg [13:0] seg
);
always @(*)
begin
    case(bin)
        4'b0000: seg = 14'b1000000_1000000; // 00
        4'b0001: seg = 14'b1000000_1111001; // 01
        4'b0010: seg = 14'b1000000_0100100; // 02
        4'b0011: seg = 14'b1000000_0110000; // 03
        4'b0100: seg = 14'b1000000_0011001; // 04
        4'b0101: seg = 14'b1000000_0010010; // 05
        4'b0110: seg = 14'b1000000_0000010; // 06
        4'b0111: seg = 14'b1000000_1111000; // 07
        4'b1000: seg = 14'b1000000_0000000; // 08
        4'b1001: seg = 14'b1000000_0010000; // 09
        4'b1010: seg = 14'b1111001_1000000; // 10
        4'b1011: seg = 14'b1111001_1111001; // 11
        4'b1100: seg = 14'b1111001_0100100; // 12
        4'b1101: seg = 14'b1111001_0110000; // 13
        4'b1110: seg = 14'b1111001_0011001; // 14
        4'b1111: seg = 14'b1111001_0010010; // 15
        default: seg = 14'b1111111_1111111;
    endcase
end
endmodule